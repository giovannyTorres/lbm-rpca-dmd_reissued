def require(condition, explanation):
    if not condition:
        raise ValueError(explanation)


def read_json(path):
    require(path.is_file(), f"Missing evidence: {path.relative_to(ROOT)}")
    with path.open(encoding="utf-8") as handle:
        value = json.load(handle)
    return value


def read_csv(path):
    require(path.is_file(), f"Missing evidence: {path.relative_to(ROOT)}")
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def finite(value, name):
    require(isinstance(value, (int, float)) and not isinstance(value, bool)
            and math.isfinite(value), f"Nonfinite or nonnumeric {name}: {value!r}")
    return float(value)


def series_max(values, name):
    valid = [finite(value, name) for value in values if value is not None]
    require(valid, f"No defined values for {name}")
    return max(valid)


def fmt(value):
    value = finite(value, "reported number")
    if value == 0:
        return "0"
    if abs(value) < .001 or abs(value) >= 10000:
        return f"{value:.3e}"
    return f"{value:.4g}"


def percent(value):
    return fmt(100 * value) + " %"


def tex_escape(value):
    result = str(value).translate(str.maketrans({
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
        "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }))
    # pdfLaTeX/Latin Modern does not have text-mode Greek glyphs. Keep the
    # generated source portable rather than relying on Unicode-math fonts.
    symbols = {"10⁻⁴": r"$10^{-4}$", "γ̇": r"$\dot\gamma$", "τxy": r"$\tau_{xy}$",
               "ν\\_s": r"$\nu_s$", "ν\\_p": r"$\nu_p$",
               "σ\\_filtro": r"$\sigma_{\mathrm{filtro}}$", "τ\\_y": r"$\tau_y$",
               "k\\_c": r"$k_c$",
               "ω": r"$\omega$", "τ": r"$\tau$", "η": r"$\eta$",
               "ν": r"$\nu$", "λ": r"$\lambda$", "κ": r"$\kappa$",
               "σ": r"$\sigma$", "ε": r"$\epsilon$", "ρ": r"$\rho$",
               "γ": r"$\gamma$", "π": r"$\pi$", "²": r"$^2$",
               "≤": r"$\leq$", "≥": r"$\geq$", "−": r"$-$", "→": r"$\to$"}
    for character, replacement in symbols.items():
        result = result.replace(character, replacement)
    return result


class Document:
    def __init__(self):
        self.markdown = ["# Mallas ampliadas y evolución física", "",
                         "Documento generado a partir de campañas completas del 14 de octubre de 2026.", ""]
        self.latex = ["% Generated by python/scripts/build_highres_chapter.py; do not edit.",
                      r"\clearpage", r"\section{Mallas ampliadas y evolución física}",
                      r"\label{sec:highres}"]
        self.sources = set()
        self.figure_count = 0

    def heading(self, title):
        self.markdown += ["## " + title, ""]
        bookmark = re.sub(r"(\d+)²", r"\1 por \1", title)
        self.latex += [r"\clearpage", r"\subsection{\texorpdfstring{" + tex_escape(title)
                       + "}{" + tex_escape(bookmark) + "}}"]

    def paragraph(self, markdown, latex=None):
        self.markdown += [markdown, ""]
        self.latex += [latex if latex is not None else tex_escape(markdown), ""]

    def table(self, headers, rows, caption, widths=None):
        self.markdown += [caption, "", "| " + " | ".join(headers) + " |",
                          "| " + " | ".join("---" for _ in headers) + " |"]
        self.markdown += ["| " + " | ".join(str(x) for x in row) + " |" for row in rows]
        self.markdown += [""]
        if widths is None:
            widths = [3.8] + [(15.0 - 3.8) / (len(headers) - 1)] * (len(headers) - 1)
        # The book has 16 cm of portrait text width. Intercolumn padding also
        # occupies space; shrink content widths slightly when seven columns
        # would otherwise extend into the margin.
        available = 15.9 - (len(headers) - 1) * 6 / 28.4527559
        if sum(widths) > available:
            widths = [round(width * available / sum(widths), 4) for width in widths]
        spec = "@{}" + "".join(r">{\raggedright\arraybackslash}p{" + str(w) + "cm}" for w in widths) + "@{}"
        self.latex += [r"\begingroup\small\setlength{\tabcolsep}{3pt}",
                       r"\begin{longtable}{" + spec + "}",
                       r"\caption{" + tex_escape(caption) + r"}\\", r"\toprule",
                       " & ".join(tex_escape(x) for x in headers) + r" \\", r"\midrule\endfirsthead",
                       r"\toprule", " & ".join(tex_escape(x) for x in headers) + r" \\",
                       r"\midrule\endhead"]
        self.latex += [" & ".join(tex_escape(x) for x in row) + r" \\" for row in rows]
        self.latex += [r"\bottomrule\end{longtable}\endgroup", ""]

    def figure(self, path, caption, label, landscape=False):
        require(path.is_file(), f"Missing final illustration: {path.relative_to(ROOT)}")
        require(path.stat().st_size > 1000, f"Empty illustration: {path.relative_to(ROOT)}")
        self.sources.add(path)
        self.figure_count += 1
        png = path.with_suffix(".png")
        require(png.is_file(), f"Missing PNG companion: {png.relative_to(ROOT)}")
        self.markdown += [f"![{caption}](../../{png.relative_to(ROOT)})", "", caption, ""]
        relative = path.relative_to(ROOT).as_posix()
        self.latex.append(r"\clearpage")
        if landscape:
            self.latex.append(r"\begin{landscape}")
            dimensions = r"width=\linewidth,height=.80\textwidth,keepaspectratio"
        else:
            dimensions = r"width=\textwidth,height=.75\textheight,keepaspectratio"
        self.latex += [r"\begin{figure}[p]\centering",
                       r"\includegraphics[" + dimensions + "]{" + relative + "}",
                       r"\caption{" + tex_escape(caption) + "}",
                       r"\label{fig:" + label + r"}\end{figure}"]
        if landscape:
            self.latex.append(r"\end{landscape}")
        self.latex.append(r"\clearpage")

    def source(self, path):
        self.sources.add(path)

    def animation(self, path, description):
        require(path.is_file(), f"Missing animation: {path.relative_to(ROOT)}")
        self.sources.add(path)
        self.markdown += [f"- [{description}](../../{path.relative_to(ROOT)})", ""]


def check_completed():
    ns_done, ve_done, vp_done, rc_done, fixed_done = [
        read_json(path / "completion.json") for path in (NS, VE, VP, RECON, FIXED)]
    require(ns_done.get("status") == "completed", "Navier–Stokes campaign is not complete")
    require(ve_done.get("complete") is True, "Viscoelastic campaign is not complete")
    require(vp_done.get("complete") is True, "Viscoplastic campaign is not complete")
    require(rc_done.get("complete") is True and rc_done.get("conditions") == 60,
            "The 60-condition reconstruction campaign is not complete")
    require(ns_done.get("failures") == 0 and rc_done.get("failed_conditions") == 0,
            "Completed campaign contains failed conditions; investigate before reporting")
    require(fixed_done.get("complete") is True and fixed_done.get("conditions") == 24
            and fixed_done.get("failed_conditions") == 0,
            "The 24-condition exploratory fixed-bandwidth follow-up is not complete")
    ns, ve = read_json(NS / "summary.json"), read_json(VE / "summary.json")
    vp, stress = read_json(VP / "comparisons.json"), read_json(VP / "derived_stress_frobenius.json")
    rc, vp_rows = read_json(RECON / "summary.json"), read_csv(VP / "summary.csv")
    fixed = read_json(FIXED / "summary.json")
    require(ns.get("status") == "completed" and ns.get("grids") == [64, 128, 256, 512]
            and ns.get("reference_nx") == 512, "Unexpected Navier–Stokes resolution corpus")
    require(ve.get("complete") is True and ve.get("grids") == [64, 128, 256],
            "Unexpected viscoelastic resolution corpus")
    require(ns["duration"] == 4 and ns["frames"] == 41 and ve["duration"] == 2.4
            and ve["snapshots"] == 25 and ve["amplitude"] == .8,
            "The dated chapter describes the T=4 / T=2.4 corpora; review the prose after changing parameters")
    require(ns["parameters"]["seed"] == 17 and math.isclose(ns["parameters"]["length_x"], 2 * math.pi)
            and math.isclose(ns["parameters"]["length_y"], 2 * math.pi),
            "Changed NS seed/domain; review the dated interpretation")
    base_config = read_json(RECON / "provenance.json")["configuration"]
    fixed_config = read_json(FIXED / "provenance.json")["configuration"]
    expected_gates = {"velocity_relative_l2": .15, "vorticity_relative_l2": .25,
                      "extra_divergence_normalized": .1, "kinetic_energy_relative_l2": .15}
    require(base_config["grids"] == fixed_config["grids"] == [128, 256]
            and base_config["seeds"] == fixed_config["seeds"] == [7, 23, 61]
            and base_config["thresholds"] == fixed_config["thresholds"] == expected_gates
            and fixed_config["physical_cutoff"] == 10 and fixed_config["rank"] == 8,
            "Changed exploratory follow-up design; review its interpretation before publishing")
    require(base_config["relative_rms"] == .2 and base_config["spatial_correlation_length"] == .1
            and base_config["spatial_master_grid"] == 256,
            "Changed reconstruction contamination design; review filter-width and RMS prose")
    for model in ("oldroyd_b", "fene_p"):
        physical = read_json(VE / "datasets" / (model + "_256.json"))["config"]["physical"]
        require(physical["viscosity_s"] == .02 and physical["viscosity_p"] == .04
                and physical["relaxation_time"] == .5 and physical["stress_diffusivity"] == 0
                and physical["extensibility_squared"] == 12,
                "Changed viscoelastic constitutive parameters; review the dated prose")
    require(vp_done.get("short_reference_state_grid") == 256,
            "The short-horizon 256² viscoplastic reference was not executed")
    require(len(vp_rows) == vp_done.get("runs"), "Viscoplastic summary does not match completed run count")
    unique = {(row["nx"], row["noise"], row["seed"], row["method"]) for row in rc}
    require(len(rc) == len(unique) == 60 and all(row.get("status") == "ok" for row in rc),
            "Missing, duplicate or failed reconstruction conditions")
    fixed_unique = {(row["nx"], row["noise"], row["seed"], row["method"]) for row in fixed}
    require(len(fixed) == len(fixed_unique) == 24 and all(row.get("status") == "ok" for row in fixed),
            "Missing, duplicate or failed fixed-bandwidth conditions")
    require(sum(row["quality_pass"] is True for row in fixed) == fixed_done.get("quality_pass_conditions"),
            "Fixed-bandwidth quality count does not match the completion record")
    for filename, expected_hash in stress["source_file_hashes"].items():
        require(hashlib.sha256((VP / filename).read_bytes()).hexdigest() == expected_hash,
                f"Stale derived Frobenius comparisons: {filename}")
    for folder in (NS, VE, VP):
        manifests = list((folder / "datasets").glob("*.json"))
        require(manifests, f"Missing dataset manifests: {folder.name}")
        for path in manifests:
            meta = read_json(path)
            require(meta.get("complete") is True or meta.get("status") == "completed",
                    f"Incomplete simulation manifest: {path.name}")
            require(path.with_suffix(".npz").is_file(), f"Missing computed field archive: {path.name}")
    require(len(ns["grid_refinement"]) == 6, "Missing nonlinear spatial comparisons")
    ns_series = read_csv(NS / "comparison_timeseries.csv")
    for row in ns["grid_refinement"]:
        times = [item for item in ns_series if item["case"] == row["case"]
                 and item["comparison"] == "spatial" and int(item["nx"]) == row["nx"]]
        require(len(times) == ns["frames"], "Incomplete NS maximum-over-time evidence")
        for quantity in ("velocity", "vorticity"):
            observed = max(finite(float(item[quantity + "_full_field_relative_l2"]), "NS timeseries") for item in times)
            require(math.isclose(observed, row["maximum_" + quantity + "_full_field_error"], rel_tol=1e-12, abs_tol=1e-15),
                    "NS summary maximum does not match its separate CSV timeseries")
    require(set(ve["spatial_refinement"]) == {"oldroyd_b", "fene_p"}, "Missing viscoelastic model")
    for rows in ve["spatial_refinement"].values():
        require({row["nx"] for row in rows} == {64, 128}, "Incomplete viscoelastic comparison to 256²")
        for row in rows:
            require(len(row["times"]) == ve["snapshots"], "Incomplete VE stored times")
            for quantity in ("velocity", "vorticity", "excess_conformation", "stress"):
                values = row[quantity + "_full_field_relative_l2"]
                require(len(values) == len(row["times"]), "Incomplete VE full-field error series")
                series_max(values, "VE full-field error")
    for row in vp:
        for error in row["errors"].values():
            values = error["full_field_per_time_relative_l2"]
            require(len(values) == len(row["times"]), "Incomplete VP full-field error series")
            require(math.isclose(series_max(values, "VP full-field error"),
                                 error["full_field_maximum_per_time_relative_l2"], rel_tol=1e-12, abs_tol=1e-15),
                    "VP stored maximum does not match the full-field timeseries")
    for row in [*rc, *fixed]:
        for metric in ("velocity_relative_l2", "vorticity_relative_l2", "kinetic_energy_relative_l2",
                       "extra_divergence_normalized"):
            require(finite(row[metric], "reconstruction " + metric) >= 0,
                    "A nonnegative reconstruction error is negative")
    return ns, ve, vp, stress, rc, fixed, vp_rows, (ns_done, ve_done, vp_done, rc_done, fixed_done)


